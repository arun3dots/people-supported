"use client";

import React from "react";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
  Badge,
  Button,
  Pagination,
  Text,
} from "@repo/ui/components/ui";
import { Download, FileText, CheckCircle2, History, ExternalLink } from "lucide-react";
import Link from "next/link";

export interface GeneratedReportLog {
  id: string;
  name: string;
  category: string;
  generatedDate: string;
  generatedBy: string;
  format: "CSV" | string;
  status: "Ready" | "Generating" | "Failed" | string;
  fileSize: string;
  filename?: string;
  content?: string;
  detailHref?: string;
}

export interface RecentReportsTableProps {
  logs: GeneratedReportLog[];
  onDownload: (log: GeneratedReportLog) => void;
  currentPage?: number;
  pageSize?: number;
  totalRecords?: number;
  onPageChange?: (page: number) => void;
  onLimitChange?: (limit: string) => void;
}

export function RecentReportsTable({
  logs,
  onDownload,
  currentPage,
  pageSize,
  totalRecords,
  onPageChange,
  onLimitChange,
}: RecentReportsTableProps) {
  return (
    <div className="bg-surface-card-grey rounded-2xl p-5 lg:p-6 flex flex-col justify-between overflow-x-auto shadow-none border-none font-sans">
      <div className="flex items-center gap-2.5 mb-4 pb-3 border-b border-border-secondary/40">
        <div className="size-8 rounded-lg bg-surface-primary-light flex items-center justify-center text-icon-primary">
          <History className="size-4" />
        </div>
        <div>
          <Text as="h3" size="md" weight="medium" className="text-slate-900">
            Recently Generated Reports
          </Text>
          <Text size="md" weight="regular" className="text-slate-500 mt-0.5">
            History of generated audit packs, clinical reviews, and data exports
          </Text>
        </div>
      </div>

      <Table className="w-full border-collapse">
        <TableHeader>
          <TableRow>
            <TableHead className="whitespace-nowrap min-w-52">Report Name</TableHead>
            <TableHead className="whitespace-nowrap min-w-36">Category</TableHead>
            <TableHead className="whitespace-nowrap min-w-32">Generated Date</TableHead>
            <TableHead className="whitespace-nowrap">Generated By</TableHead>
            <TableHead className="whitespace-nowrap">Format</TableHead>
            <TableHead className="whitespace-nowrap">Status</TableHead>
            <TableHead className="whitespace-nowrap text-right">Action</TableHead>
          </TableRow>
        </TableHeader>

        <TableBody>
          {logs.length === 0 ? (
            <TableRow>
              <TableCell colSpan={7} className="py-12 text-center">
                <FileText className="size-8 text-slate-300 mx-auto mb-1.5" />
                <Text size="md" weight="medium" className="text-slate-500">
                  No generated reports yet
                </Text>
              </TableCell>
            </TableRow>
          ) : (
            logs.map((log) => (
              <TableRow key={log.id} className="hover:bg-slate-50/70 transition-colors">
                {/* Report Name */}
                <TableCell className="py-3.5">
                  <div className="flex items-center gap-3 min-w-0">
                    <div className="size-10 rounded-full bg-surface-primary-light text-icon-primary border border-emerald-100/60 flex items-center justify-center font-bold text-md shrink-0">
                      <FileText className="size-5 text-icon-primary" />
                    </div>
                    <div className="flex flex-col min-w-0 gap-0.5">
                      <Text
                        size="md"
                        weight="medium"
                        className="text-slate-900 truncate max-w-60"
                      >
                        {log.name}
                      </Text>
                      <Text size="md" weight="regular" className="text-slate-400 font-mono">
                        {log.fileSize}
                      </Text>
                    </div>
                  </div>
                </TableCell>

                {/* Category */}
                <TableCell className="py-3.5">
                  <Badge
                    variant="secondary"
                    state="info"
                    className="px-2.5 py-0.5 shadow-none"
                  >
                    {log.category}
                  </Badge>
                </TableCell>

                {/* Date */}
                <TableCell className="py-3.5">
                  <Text size="md" weight="regular" className="text-slate-700">
                    {log.generatedDate}
                  </Text>
                </TableCell>

                {/* Generated By */}
                <TableCell className="py-3.5">
                  <Text size="md" weight="regular" className="text-slate-700">
                    {log.generatedBy}
                  </Text>
                </TableCell>

                {/* Format */}
                <TableCell className="py-3.5">
                  <Badge variant="secondary" state="inactive" className="font-mono px-2 py-0.5 shadow-none">
                    {log.format}
                  </Badge>
                </TableCell>

                {/* Status */}
                <TableCell className="py-3.5">
                  <Badge
                    variant="secondary"
                    state="success"
                    className="px-2.5 py-0.5 shadow-none"
                  >
                    <CheckCircle2 className="size-3 mr-1" />
                    {log.status}
                  </Badge>
                </TableCell>

                {/* Action */}
                <TableCell className="py-3.5 text-right">
                  <div className="inline-flex items-center gap-2">
                    {log.detailHref && (
                      <Link
                        href={log.detailHref}
                        className="inline-flex items-center gap-1.5 rounded-xl h-8 px-3 text-sm font-medium border border-slate-200 bg-white text-slate-700 hover:bg-slate-50"
                      >
                        <ExternalLink className="size-3.5" />
                        View Details
                      </Link>
                    )}
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => onDownload(log)}
                      className="rounded-xl gap-1.5 shadow-none border-slate-200 bg-white hover:bg-slate-50 cursor-pointer"
                    >
                      <Download className="size-3.5" />
                      Download
                    </Button>
                  </div>
                </TableCell>
              </TableRow>
            ))
          )}
        </TableBody>
      </Table>

      {totalRecords !== undefined &&
        currentPage !== undefined &&
        pageSize !== undefined &&
        onPageChange &&
        onLimitChange &&
        totalRecords > 0 && (
          <div className="pt-4 border-t border-border-secondary/50 mt-4">
            <Pagination
              pageNumber={currentPage}
              pageSize={pageSize}
              totalRecords={totalRecords}
              limit={pageSize.toString()}
              onPageChange={onPageChange}
              onLimitChange={onLimitChange}
            />
          </div>
        )}
    </div>
  );
}
